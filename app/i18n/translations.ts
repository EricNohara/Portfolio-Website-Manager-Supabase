export function isAppLanguage(value: string): value is AppLanguage {
  return value === "de" || value === "en" || value === "es" || value === "fr" || value === "ja";
}

export function normalizeLanguage(value: string | null): AppLanguage {
  if (!value) return DEFAULT_LANGUAGE;
  if (isAppLanguage(value)) return value;
  return LEGACY_LANGUAGE_VALUES[value] ?? DEFAULT_LANGUAGE;
}

export function applyDocumentLanguage(language: AppLanguage) {
  document.documentElement.lang = HTML_LANGUAGE_CODES[language];
}

export function getStoredLanguage(): AppLanguage {
  return normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY));
}

export function setStoredLanguage(language: AppLanguage) {
  localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
}

export function translate(language: AppLanguage, message: string) {
  return translations[language][message] ?? message;
}
